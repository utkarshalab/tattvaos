#!/usr/bin/env python3
"""Static ELF linking into the existing NASM-flat ULF image.

prepare: link the isolated shell at provisional addresses, export sizes/offsets.
patch: link it again at addresses assigned by NASM; replace initialized sections.
No handwritten relocations, executable data, fixed load address, or second full
kernel assembly. ld applies every app relocation. ULF stamping happens afterward.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import struct
import subprocess
import tempfile

ROOT=Path(__file__).resolve().parents[3]
OUT=ROOT/'apps/ush/build/kernel'
OBJECT=ROOT/'apps/ush/build/ush-native.o'
MAGIC=b'UTKUSH_LAYOUT_V1\0'
SECTIONS=('text','rodata','data','bss')

def run(*args):
    return subprocess.check_output([str(x) for x in args],text=True)

def symbols(elf):
    result={}
    for line in run('nm','-P',elf).splitlines():
        parts=line.split()
        if len(parts)>=3:
            result[parts[0]]=int(parts[2],16)
    return result

def link(directory,addresses,obj):
    script=[]
    for name,address in zip(SECTIONS,addresses):
        contents={
            'text':'*(.text*)',
            'rodata':'*(.rodata*) *(.data.rel.ro*)',
            'data':'*(.data*)',
            'bss':'*(.bss*) *(COMMON)',
        }[name]
        script.append(f'.{name} {address:#x} : {{ __ush_{name}_start = .; {contents} . = ALIGN(64); __ush_{name}_end = .; }}')
    script.append('/DISCARD/ : { *(.note*) *(.comment*) }')
    ldscript=directory/'ush.ld'
    ldscript.write_text('SECTIONS {\n'+'\n'.join(script)+'\n}\n')
    elf=directory/'ush.elf'
    run('ld','-z','noexecstack','-T',ldscript,'-o',elf,obj)
    names=symbols(elf)
    blobs={}
    sizes={}
    for name in SECTIONS:
        sizes[name]=names[f'__ush_{name}_end']-names[f'__ush_{name}_start']
        if name!='bss':
            path=directory/(name+'.bin')
            run('objcopy','-O','binary','--only-section=.'+name,elf,path)
            blobs[name]=path.read_bytes()
            if len(blobs[name])!=sizes[name]:
                raise ValueError(f'{name}: section extent mismatch')
    return names,sizes,blobs

def publish(path,data):
    tmp=path.with_name(path.name+f'.{os.getpid()}.tmp')
    tmp.write_bytes(data)
    tmp.replace(path)

def prepare():
    OUT.mkdir(parents=True,exist_ok=True)
    # Immutable object copy prevents a concurrent app rebuild from changing the
    # exact source bytes between the sizing and final address-link steps.
    objbytes=OBJECT.read_bytes()
    with tempfile.TemporaryDirectory(dir=OUT) as work:
        work=Path(work)
        obj=work/'input.o'
        obj.write_bytes(objbytes)
        addresses=[0x1000000,0x1100000,0x1200000,0x1300000]
        names,sizes,blobs=link(work,addresses,obj)
    offsets={
        'MAIN':names['ush_main']-addresses[0],
        'LOG_BEGIN':names['line_log_begin']-addresses[0],
        'LOG_END':names['line_log_end']-addresses[0],
        'UART':names['uart_frontend']-addresses[2],
        'IDLE_HOOK':names['uart_idle_hook']-addresses[3],
        'CLOCK_HOOK':names['ush_clock_hook']-addresses[3],
        'SLEEP_HOOK':names['ush_sleep_hook']-addresses[3],
        'POWER_HOOK':names['ush_power_hook']-addresses[3],
    }
    for name,blob in blobs.items():
        publish(OUT/(name+'.bin'),blob)
    publish(OUT/'input.o',objbytes)
    manifest={'sizes':sizes,'offsets':offsets,'sha256':hashlib.sha256(objbytes).hexdigest()}
    publish(OUT/'manifest.json',json.dumps(manifest,indent=2).encode())
    header='; Generated by scripts/kernel_bundle.py; do not edit.\n'
    for name,size in sizes.items():
        header+=f'KERNEL_USH_{name.upper()}_SIZE equ {size}\n'
    for name,value in offsets.items():
        header+=f'KERNEL_USH_{name}_OFFSET equ {value}\n'
    # Header is published last; Make treats it as the preparation target.
    publish(OUT/'layout.inc',header.encode())
    print('Ush sections prepared:',sizes)

def patch(kernel):
    manifest=json.loads((OUT/'manifest.json').read_text())
    obj=OUT/'input.o'
    if hashlib.sha256(obj.read_bytes()).hexdigest()!=manifest['sha256']:
        raise ValueError('prepared object changed')
    raw=bytearray(kernel.read_bytes())
    at=raw.find(MAGIC)
    if at<0 or raw.find(MAGIC,at+1)>=0:
        raise ValueError('expected exactly one Ush layout marker')
    values=struct.unpack_from('<8Q',raw,at+len(MAGIC))
    addresses=values[:4]
    sizes=dict(zip(SECTIONS,values[4:]))
    if sizes!=manifest['sizes']:
        raise ValueError('kernel/app sizes disagree; rebuild preparation')
    base=0x100000
    exec_end=base+struct.unpack_from('<I',raw,24)[0]
    memory_end=base+struct.unpack_from('<Q',raw,32)[0]
    ranges=[]
    for name,address in zip(SECTIONS,addresses):
        end=address+sizes[name]
        if address%64 or address<base or end>memory_end:
            raise ValueError(f'invalid {name} memory range')
        if name=='text' and end>exec_end:
            raise ValueError('shell instructions outside executable ULF prefix')
        if name!='text' and address<exec_end:
            raise ValueError('shell data overlaps executable ULF prefix')
        if name!='bss' and end>base+len(raw):
            raise ValueError('initialized shell section outside file')
        ranges.append((address,end))
    for a,b in zip(sorted(ranges),sorted(ranges)[1:]):
        if a[1]>b[0]:
            raise ValueError('overlapping shell ranges')
    with tempfile.TemporaryDirectory(dir=OUT) as work:
        _,actual,blobs=link(Path(work),addresses,obj)
    if actual!=sizes:
        raise ValueError('link changed section sizes')
    for name,address in zip(SECTIONS,addresses):
        if name!='bss':
            offset=address-base
            raw[offset:offset+sizes[name]]=blobs[name]
    # The ULF checksum consumes qwords. Final read-only diagnostic strings can
    # leave the flat file unaligned; append zeros without moving any section.
    # Those bytes were already zero-owned memory in the loader's BSS aperture.
    padding=(-len(raw))%8
    if base+len(raw)+padding>memory_end:
        raise ValueError('checksum padding exceeds owned memory')
    raw.extend(bytes(padding))
    kernel.write_bytes(raw)
    publish(OUT/'linked-layout.json',json.dumps({'addresses':dict(zip(SECTIONS,addresses)),'sizes':sizes},indent=2).encode())
    print('Ush linked at kernel-owned addresses:',*[hex(a) for a in addresses])

if __name__=='__main__':
    ap=argparse.ArgumentParser()
    ap.add_argument('action',choices=['prepare','patch'])
    ap.add_argument('kernel',nargs='?',type=Path)
    args=ap.parse_args()
    if args.action=='prepare':
        prepare()
    else:
        if args.kernel is None:
            ap.error('patch requires a temporary kernel image')
        patch(args.kernel)
