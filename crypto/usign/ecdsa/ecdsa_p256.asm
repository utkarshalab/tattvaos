%ifndef GUARD_CRYPTO_USIGN_ECDSA_ECDSA_P256_ASM
%define GUARD_CRYPTO_USIGN_ECDSA_ECDSA_P256_ASM
; =============================================================================
; Tattva OS — crypto/usign/ecdsa/ecdsa_p256.asm
; =============================================================================
; ECDSA over NIST P-256 (secp256r1) — signing and verification.
;
; Implements:
;   - Point arithmetic in Jacobian coordinates (`p256_dbl`, `p256_add`)
;   - Scalar multiplication, variable and constant time
;   - Verification (`ecdsa_p256_verify`, `ecdsa_p256_verify_der`)
;   - Signing (`ecdsa_p256_sign`, `ecdsa_p256_sign_der`)
;   - Key generation (`ecdsa_p256_keygen`)
;   - DER encode and strict decode
;
; The curve is y^2 = x^3 - 3x + b over GF(p), p = 2^256 - 2^224 + 2^192 + 2^96 - 1.
; The a = -3 choice is not cosmetic: it lets the doubling formula replace a
; multiplication by a with a subtraction, which is why every standard P-256
; implementation uses these specific formulas.
;
; JACOBIAN COORDINATES (X : Y : Z) represent the affine point (X/Z^2, Y/Z^3).
; Carrying Z avoids a modular inversion per operation; one inversion at the end
; converts back. Note the SQUARE and CUBE — treating Jacobian coordinates as if
; they were the projective (X/Z, Y/Z) kind produces points that are consistently
; wrong and no test of the group law alone will notice.
;
; VERIFICATION:
;   reject unless 1 <= r < n and 1 <= s < n
;   w  = s^-1 mod n
;   u1 = e*w mod n,  u2 = r*w mod n
;   R  = u1*G + u2*Q      (reject if the identity)
;   accept iff R.x mod n == r
;
; e IS THE LEFTMOST bitlen(n) BITS OF THE HASH, not the hash modulo n. For
; P-256 with SHA-256 both are 256 bits, so e is the whole digest read big-endian
; — but it must then be reduced mod n before use as a scalar, since a digest can
; exceed n.
;
; TWO SCALAR MULTIPLICATIONS, DELIBERATELY. `p256_scalarmult` is variable time
; and is used by verification, where every input is public. `p256_scalarmult_ct`
; is used wherever the scalar is secret — signing and key derivation. The
; difference is not an optimisation: sharing the fast one would leak the private
; key through timing while still producing perfectly valid signatures, so
; nothing would appear wrong.
;
; The variable-time addition also BRANCHES on its inputs to handle the cases the
; Jacobian formula cannot (P == Q, P == -Q, an identity operand). Those branches
; are why it cannot be reused for secrets; `p256_add_ct` computes every case and
; selects with a mask instead.
;
; NONCES ARE DETERMINISTIC (RFC 6979). ECDSA loses the private key outright if a
; nonce ever repeats, and leaks it to lattice attacks if nonces are merely
; biased. Deriving k from the key and the message removes the RNG from signing
; entirely — see rfc6979.asm.
;
; Author:  Utkarsha Labs
; Target:  x86-64 (64-bit NASM)
; =============================================================================

[BITS 64]

%include "crypto/usign/ecdsa/bn256.asm"
%include "crypto/usign/ecdsa/rfc6979.asm"

; A Jacobian point is three field elements.
%define P256_X      0
%define P256_Y      32
%define P256_Z      64
%define P256_PT     96

section .data
align 32

; Generated by scratchpad/p256_gen.py, which verifies that G lies on the curve
; and has order n before emitting anything.
global p256_p
p256_p:         dq 0xFFFFFFFFFFFFFFFF, 0x00000000FFFFFFFF, \
                   0x0000000000000000, 0xFFFFFFFF00000001
global p256_n
p256_n:         dq 0xF3B9CAC2FC632551, 0xBCE6FAADA7179E84, \
                   0xFFFFFFFFFFFFFFFF, 0xFFFFFFFF00000000
p256_b:         dq 0x3BCE3C3E27D2604B, 0x651D06B0CC53B0F6, \
                   0xB3EBBD55769886BC, 0x5AC635D8AA3A93E7
p256_gx:        dq 0xF4A13945D898C296, 0x77037D812DEB33A0, \
                   0xF8BCE6E563A440F2, 0x6B17D1F2E12C4247
p256_gy:        dq 0xCBB6406837BF51F5, 0x2BCE33576B315ECE, \
                   0x8EE7EB4A7C0F9E16, 0x4FE342E2FE1A7F9B
p256_mu_p:      dq 0x0000000000000003, 0xFFFFFFFEFFFFFFFF, \
                   0xFFFFFFFEFFFFFFFE, 0x00000000FFFFFFFF, \
                   0x0000000000000001
p256_mu_n:      dq 0x012FFD85EEDF9BFE, 0x43190552DF1A6C21, \
                   0xFFFFFFFEFFFFFFFF, 0x00000000FFFFFFFF, \
                   0x0000000000000001
p256_p_m2:      dq 0xFFFFFFFFFFFFFFFD, 0x00000000FFFFFFFF, \
                   0x0000000000000000, 0xFFFFFFFF00000001
p256_n_m2:      dq 0xF3B9CAC2FC63254F, 0xBCE6FAADA7179E84, \
                   0xFFFFFFFFFFFFFFFF, 0xFFFFFFFF00000000
p256_one:       dq 1, 0, 0, 0
p256_three:     dq 3, 0, 0, 0

section .text

global ecdsa_p256_verify
global ecdsa_p256_verify_der
global ecdsa_p256_sig_from_der
global ecdsa_p256_sig_to_der
global ecdsa_p256_sign
