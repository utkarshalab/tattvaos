; ============================================================================
; Unit Test — Colour (src/color/icc_parse.asm, matrix.asm, trc.asm)
; ============================================================================
; test_icc_suite -> eax = failed cases (each case returns 0 / 1).
; ICC: the signature at offset 36, short and unsigned data refused. Matrices
; (16.16): identity, a product, applying one to r, g, b. Curves: linear,
; gamma 2.0, a table. sRGB (COL-01): the tables exact, every code back to
; itself. Embedded profiles into sRGB (COL-02): pixels against a model of
; the reference formulas written apart from it (P3 colorants with a para 2,
; a 5-entry table and a gamma curve; grey para 1 and an identity curve); the
; sRGB curve as a grey profile, no transform; a Lab connection space and a
; profile cut short, none.

