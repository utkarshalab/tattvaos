%define ONE 0x10000
%define ICC_STORAGE 65536

section .text

global test_icc_suite
global test_icc_main
test_icc_suite:
test_icc_main:
    push rbx
    xor ebx, ebx
%macro CASE 1
    call %1
    add ebx, eax
%endmacro
    CASE tc_probe
    CASE tc_probe_reject
    CASE tm_identity
    CASE tm_mul
    CASE tm_apply
    CASE tt_linear
    CASE tt_gamma2
    CASE tt_table
    CASE ts_tables
    CASE ti_mixed
    CASE ti_grey_para1
    CASE ti_grey_linear
    CASE ti_none
    mov eax, ebx
    pop rbx
    ret

%macro PASS 0
    xor eax, eax
    add rsp, 8
    ret
.fail:
    mov eax, 1
    add rsp, 8
    ret
%endmacro

; sRGB's tables: four codes' linear values, and every code's linear value
; encoded back to it
ts_tables:
    sub rsp, 8
    call srgb_init
    lea rsi, [rel srgb_to_linear_lut]
    cmp word [rsi + 2], 20
    jne .fail
    cmp word [rsi + 20], 199
    jne .fail
    cmp word [rsi + 256], 14146
    jne .fail
    cmp word [rsi + 508], 64952
    jne .fail
    lea rdi, [rel srgb_encode_lut]
    xor ecx, ecx
.code:
    movzx eax, word [rsi + rcx * 2]
    movzx eax, byte [rdi + rax]
    cmp eax, ecx
    jne .fail
    inc ecx
    cmp ecx, 256
    jb .code
    PASS

; a profile, its length, the pixels expected -> eax = 0 they are made
%macro TRANSFORM 2
    lea rsi, [rel %1]
    mov edx, %1_len
    call build
    test rax, rax
    jz .fail
    mov rdi, rax
    call run
    lea rsi, [rel %2]
    call same
    jne .fail
%endmacro
ti_mixed:
    sub rsp, 8
    TRANSFORM icc_mixed, icc_mixed_expected
    PASS
ti_grey_para1:
    sub rsp, 8
    TRANSFORM icc_grey_para1, icc_grey_para1_expected
    PASS
ti_grey_linear:
    sub rsp, 8
    TRANSFORM icc_grey_linear, icc_grey_linear_expected
    PASS

; no transform: the sRGB curve, a Lab connection space, cut short
ti_none:
    sub rsp, 8
    lea rsi, [rel icc_grey_srgb]
    mov edx, icc_grey_srgb_len
    call build
    test rax, rax
    jnz .fail
    lea rdi, [rel icc_copy]
    lea rsi, [rel icc_mixed]
    mov ecx, icc_mixed_len
    rep movsb
    mov dword [rel icc_copy + 20], 'Lab '
    lea rsi, [rel icc_copy]
    mov edx, icc_mixed_len
    call build
    test rax, rax
    jnz .fail
    lea rsi, [rel icc_mixed]
    mov edx, icc_mixed_len - 40
    call build
    test rax, rax
    jnz .fail
    PASS

; rsi = a profile, edx = its length -> rax = icc_transform_build's, in a
; fresh arena
build:
    push rsi
    push rdx
    sub rsp, 8
    lea rdi, [rel icc_arena]
    lea rsi, [rel icc_storage]
    mov edx, ICC_STORAGE
    call arena_init
    add rsp, 8
    pop rdx
    pop rsi
    lea rdi, [rel icc_arena]
    jmp icc_transform_build

; rdi = a transform: icc_pixels copied and transformed in icc_image
run:
    push rdi
    lea rdi, [rel icc_work]
    lea rsi, [rel icc_pixels]
    mov ecx, 24
    rep movsb
    lea rsi, [rel icc_image]
    mov qword [rsi + PixBuf.width], 6
    mov qword [rsi + PixBuf.height], 1
    mov qword [rsi + PixBuf.stride], 24
    lea rax, [rel icc_work]
    mov [rsi + PixBuf.data], rax
    pop rdi
    jmp icc_transform_pixbuf

; rsi = 24 bytes expected -> ZF set when icc_work is they
same:
    lea rdi, [rel icc_work]
    mov ecx, 24
    repe cmpsb
    ret

; a 132-byte header with a size and 'acsp' at offset 36
header:
    lea rdi, [rel icc]
    xor eax, eax
    mov ecx, 132
    rep stosb
    mov dword [rel icc], 0x84000000
    mov dword [rel icc + 36], 'acsp'
    ret

tc_probe:
    sub rsp, 8
    call header
    lea rdi, [rel icc]
    mov esi, 132
    call icc_probe
    cmp rax, 1
    jne .fail
    PASS

tc_probe_reject:
    sub rsp, 8
    call header
    lea rdi, [rel icc]
    mov esi, 131                        ; too short
    call icc_probe
    test rax, rax
    jnz .fail
    mov dword [rel icc + 36], 'xcsp'
    lea rdi, [rel icc]
    mov esi, 132
    call icc_probe
    test rax, rax
    jnz .fail
    call header
    mov dword [rel icc], 0              ; no size
    lea rdi, [rel icc]
    mov esi, 132
    call icc_probe
    test rax, rax
    jnz .fail
    PASS

tm_identity:
    sub rsp, 8
    lea rdi, [rel m_a]
    call mat3_identity
    lea rdi, [rel m_a]
    mov esi, ONE / 2
    mov edx, ONE / 4
    mov ecx, 3 * ONE
    call mat3_apply
    cmp rax, ONE / 2
    jne .fail
    cmp rdx, ONE / 4
    jne .fail
    cmp rcx, 3 * ONE
    jne .fail
    PASS

tm_mul:
    sub rsp, 8
    lea rdi, [rel m_c]
    lea rsi, [rel m_scale]
    lea rdx, [rel m_shear]
    call mat3_mul
    ; scale(2, 3, 4) * shear: rows of the shear scaled
    cmp dword [rel m_c + 0], 2 * ONE
    jne .fail
    cmp dword [rel m_c + 4], ONE
    jne .fail
    cmp dword [rel m_c + 16], 3 * ONE
    jne .fail
    cmp dword [rel m_c + 32], 4 * ONE
    jne .fail
    cmp dword [rel m_c + 12], 0
    jne .fail
    PASS

tm_apply:
    sub rsp, 8
    lea rdi, [rel m_rows]
    mov esi, ONE
    mov edx, 2 * ONE
    mov ecx, 3 * ONE
    call mat3_apply
    cmp rax, 14 * ONE                   ; 1 + 4 + 9
    jne .fail
    cmp rdx, 2 * ONE                    ; the middle row keeps g
    jne .fail
    cmp rcx, 6 * ONE                    ; 1 + 2 + 3
    jne .fail
    PASS

tt_linear:
    sub rsp, 8
    lea rdi, [rel trc]
    call trc_init_linear
    lea rdi, [rel trc]
    mov esi, 0x4000
    call trc_apply
    cmp rax, 0x4000
    jne .fail
    PASS

tt_gamma2:
    sub rsp, 8
    lea rdi, [rel trc]
    mov esi, 2 * ONE
    call trc_init_gamma
    lea rdi, [rel trc]
    mov esi, ONE / 2                    ; 0.5 ^ 2
    call trc_apply
    cmp rax, ONE / 4
    jne .fail
    PASS

tt_table:
    sub rsp, 8
    lea rdi, [rel trc]
    lea rsi, [rel curve]
    mov edx, 4
    call trc_init_table
    lea rdi, [rel trc]
    mov esi, ONE / 2                    ; index 2
    call trc_apply
    cmp rax, 3000
    jne .fail
    lea rdi, [rel trc]
    mov esi, ONE                        ; the top
    call trc_apply
    cmp rax, ONE
    jne .fail
    PASS

