global test_jpeg_sampling
; jpeg_upsample_row against the reference decoders' formulas, worked out
; apart from it: a 4x2 plane (stride 8, the rest 999, never read) at 2x2,
; 2x1, 1x2 and a third across (samples repeated), 7 samples a row wanted at
; half width (the last half-sample dropped), and all 8 once; a factor of 0
; refused
test_jpeg_sampling:
    PROLOGUE_SAVE rbx, r12, r13, r14, r15
    sub rsp, 8
    lea r12, [rel up_cases]
    lea rax, [rel up_plane]
    mov [rel up_desc + JpegPlane.data], rax
    mov dword [rel up_desc + JpegPlane.stride], 8
    mov dword [rel up_desc + JpegPlane.width], 4
    mov dword [rel up_desc + JpegPlane.height], 2
.case:
    mov eax, [r12]                      ; h, v, max h, max v
    test eax, eax
    jz .refuse
    mov [rel up_desc + JpegPlane.h], al
    mov [rel up_desc + JpegPlane.v], ah
    shr eax, 16
    mov [rel up_desc + JpegPlane.max_h], al
    mov [rel up_desc + JpegPlane.max_v], ah
    movzx ebx, byte [r12 + 4]           ; rows
    movzx r13d, byte [r12 + 5]          ; samples a row
    lea r15, [r12 + 8]                  ; expected
    xor r14d, r14d                      ; y
.row:
    lea rdi, [rel up_desc]
    mov esi, r14d
    lea rdx, [rel up_out]
    mov ecx, r13d
    call jpeg_upsample_row
    test rax, rax
    jnz .fail
    xor ecx, ecx
.sample:
    lea rdx, [rel up_out]
    movzx edx, word [rdx + rcx * 2]
    cmp dx, [r15 + rcx * 2]
    jne .fail
    inc ecx
    cmp ecx, r13d
    jb .sample
    lea r15, [r15 + r13 * 2]
    inc r14d
    cmp r14d, ebx
    jb .row
    mov r12, r15
    jmp .case
.refuse:
    mov byte [rel up_desc + JpegPlane.h], 0
    lea rdi, [rel up_desc]
    xor esi, esi
    lea rdx, [rel up_out]
    mov ecx, 4
    call jpeg_upsample_row
    cmp rax, -EINVAL
    jne .fail
    xor eax, eax
    jmp .out
.fail:
    mov eax, 1
.out:
    add rsp, 8
    EPILOGUE_RESTORE rbx, r12, r13, r14, r15

; MED-20: progressive JPEGs made from a baseline one without loss (jpegtran:
; the very same coefficients) decode to exactly its pixels: 24x16 4:2:0 by
; the default script (successive approximation of DC and AC), with a
; restart after every block, and by a script of DC scans one component
; each, split bands, AC first at Al 2 then two refines, a chroma band
; refined; and two grey ones, the second 64x48 (end-of-band runs ending
; before the scan does). Cut short in a scan: refused, no harm
global test_jpeg_progressive
test_jpeg_progressive:
    PROLOGUE_SAVE rbx, r12
    lea rdi, [rel pj_arena]
    lea rsi, [rel pj_storage]
    mov edx, PJ_STORAGE
    call arena_init
    test eax, eax
    jnz .fail
%macro PJ_DECODE 1                      ; -> rax = its image
    lea rdi, [rel pj_arena]
    lea rsi, [rel %1]
    mov edx, %1_len
    call jpeg_decode
    test rax, rax
    jle .fail
%endmacro
%macro PJ_SAME 1                        ; as the baseline one, r12
    PJ_DECODE %1
    mov rdi, r12
    mov rsi, rax
    call pj_same
    test eax, eax
    jnz .fail
%endmacro
    PJ_DECODE pj_base
    mov r12, rax
    PJ_SAME pj_prog
    PJ_SAME pj_restart
    PJ_SAME pj_script
    PJ_DECODE pj_grey_base
    mov r12, rax
    PJ_SAME pj_grey_prog
    PJ_DECODE pj_grey64_base
    mov r12, rax
    PJ_SAME pj_grey64_prog
    lea rdi, [rel pj_arena]
    lea rsi, [rel pj_prog]
    mov edx, pj_prog_len / 2
    call jpeg_decode
    test rax, rax
    jnz .fail
    xor eax, eax
    jmp .out
.fail:
    mov eax, 1
.out:
    EPILOGUE_RESTORE rbx, r12

; rdi, rsi = PixBufs -> eax = 0 the same size and pixels
pj_same:
    mov rax, [rdi + PixBuf.width]
    cmp rax, [rsi + PixBuf.width]
    jne .differ
    mov rax, [rdi + PixBuf.height]
    cmp rax, [rsi + PixBuf.height]
    jne .differ
    xor r8d, r8d                        ; y
.row:
    cmp r8, [rdi + PixBuf.height]
    jae .same
    mov r9, r8
    imul r9, [rdi + PixBuf.stride]
    add r9, [rdi + PixBuf.data]
    mov r10, r8
    imul r10, [rsi + PixBuf.stride]
    add r10, [rsi + PixBuf.data]
    xor ecx, ecx
.pixel:
    mov eax, [r9 + rcx * 4]
    cmp eax, [r10 + rcx * 4]
    jne .differ
    inc rcx
    cmp rcx, [rdi + PixBuf.width]
    jb .pixel
    inc r8
    jmp .row
.same:
    xor eax, eax
    ret
.differ:
    mov eax, 1
    ret

