#!/usr/bin/env python3
"""Golden frame checksums for tests/unit/test_golden.asm (QA-02).

Usage: make_golden.py [out.inc]   (default tests/golden/expected/golden.inc)
       make_golden.py --check     (the file is up to date; exit 1 if not)

A model of Canvas's compositor, written apart from it: the background, then
each surface in order over a 64x48 output, clipped to it; a surface whose
buffer has no alpha (BGRX) is copied, any other blended premultiplied
"over" with the rounding blend_over_premul uses:
    out = min(255, src + div255(dst * (255 - alpha))),
    div255(t) = (t + 128 + ((t + 128) >> 8)) >> 8.
Each scene's checksum is the Adler-32 of the framebuffer's bytes. The
first scene is the one GOLDEN_FIRST was computed for, so the model is
checked against a value that predates it.

Development-machine tooling only; not part of any OS image.
"""
import os
import struct
import sys
import zlib

W, H, BG = 64, 48, 0xFF202030


def div255(t):
    return (t + 128 + ((t + 128) >> 8)) >> 8


def over(dst, src):
    a = src >> 24
    if a == 255:
        return src
    out = 0
    for shift in (0, 8, 16, 24):
        d = (dst >> shift) & 255
        s = (src >> shift) & 255
        out |= min(255, s + div255(d * (255 - a))) << shift
    return out


def gradient(x, y):
    """Scene A's pixels: 0xFF, x * 4, y * 8, 0x10."""
    return 0xFF000010 | (((x * 4) & 255) << 16) | (((y * 8) & 255) << 8)


def compose(surfaces):
    fb = [BG] * (W * H)
    for sx, sy, w, h, pixel, opaque in surfaces:
        for y in range(h):
            for x in range(w):
                ox, oy = sx + x, sy + y
                if 0 <= ox < W and 0 <= oy < H:
                    src = pixel(x, y)
                    i = oy * W + ox
                    fb[i] = src if opaque else over(fb[i], src)
    return zlib.adler32(struct.pack(f'<{W * H}I', *fb)) & 0xFFFFFFFF


def solid(c):
    return lambda x, y: c


SCENES = {
    # test_golden's first scene: A, 32x24 at (8, 8); B, 16x16 at (24, 16)
    'FIRST': [(8, 8, 32, 24, gradient, False), (24, 16, 16, 16, solid(0x80004000), False)],
    # three translucent rectangles stacked, each over the last
    'STACK': [(4, 4, 20, 20, solid(0x80800000), False),
              (12, 10, 24, 18, solid(0x40004040), False),
              (20, 6, 30, 14, solid(0xC0101060), False)],
    # an opaque BGRX buffer (copied, not blended), a translucent one over it
    'OPAQUE': [(10, 10, 30, 20, gradient, True),
               (30, 20, 20, 20, solid(0x60202020), False)],
    # one over each edge and corner of the output
    'EDGES': [(-6, -4, 16, 12, solid(0xFF0000FF), False),
              (56, -5, 14, 14, solid(0x80008000), False),
              (-8, 40, 20, 12, solid(0xA0500000), False),
              (58, 42, 10, 10, solid(0x40404040), False)],
}


def render():
    lines = ['; Generated by tests/golden/make_golden.py: do not edit.',
             '; Adler-32 of each golden scene\'s 64x48 frame.']
    for name, surfaces in SCENES.items():
        lines.append(f'%define GOLDEN_{name:<8} 0x{compose(surfaces):08X}')
    return '\n'.join(lines) + '\n'


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    path = os.path.join(here, 'expected', 'golden.inc')
    text = render()
    if '--check' in sys.argv:
        same = os.path.exists(path) and open(path).read() == text
        print('make_golden: up to date' if same else 'make_golden: golden.inc is out of date')
        return 0 if same else 1
    if len(sys.argv) > 1:
        path = sys.argv[1]
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, 'w', newline='\n').write(text)
    print(text, end='')
    return 0


if __name__ == '__main__':
    sys.exit(main())
