#!/usr/bin/env python3
"""Generate inc/cwp_ops.inc and inc/cwp_dispatch.inc from the protocol files.

Usage: cwpgen.py [--check] -o inc/cwp_ops.inc [-d inc/cwp_dispatch.inc]
                 [--handlers src/server/server_core.asm] proto/a.cwp ...

Each request and event gets the number of its place in its interface, as
the wire carries it in hdr.opcode: requests as <INTERFACE>_<REQUEST>, events
as <INTERFACE>_EV_<EVENT>, the interface named without its cw_ prefix.

The dispatch file is one macro, CWP_REGISTER_ALL, which for every request
invokes CWP_REQUEST CWP_OBJ_<INTERFACE>, <INTERFACE>_<REQUEST>,
h_<interface>_<request> if HAVE_h_<interface>_<request> is defined: the
server defines it as it builds each handler, so the requests it handles are
registered and no others, and a handler's name says which request it is.

With --check nothing is written: the exit status is 1 if a file on disk is
not what would be written, so a protocol change cannot leave them behind.
With --handlers it is 1 too if that file defines a handler (HANDLER and the
macros built on it) no request is named for: it would never be registered.

Development-machine tooling only; not part of any OS image.
"""
import argparse
import os
import re
import sys

R_INTERFACE = re.compile(r'^\s*interface\s+(\w+)\s+\d+\s*\{')
R_REQUEST = re.compile(r'^\s*request\s+(\w+)\s*\(')
R_EVENT = re.compile(r'^\s*event\s+(\w+)\s*\(')


def interfaces(path):
    """[(interface, [requests], [events])] in the order the file has them."""
    found = []
    current = None
    depth = 0
    for line in open(path, encoding='utf-8'):
        code = line.split(';')[0]
        if current is None:
            m = R_INTERFACE.match(code)
            if m:
                current = (m[1], [], [])
                depth = code.count('{') - code.count('}')
            continue
        m = R_REQUEST.match(code)
        if m and depth == 1:
            current[1].append(m[1])
        m = R_EVENT.match(code)
        if m and depth == 1:
            current[2].append(m[1])
        depth += code.count('{') - code.count('}')
        if depth == 0:
            found.append(current)
            current = None
    if current is not None:
        sys.exit(f'{path}: interface {current[0]} is not closed')
    return found


def banner(title, paths, lines):
    return [
        '; ============================================================================',
        f'; {title}',
        '; ============================================================================',
        '; Generated by tools/cwpgen.py from '
        + ', '.join(os.path.basename(p) for p in paths) + ';',
        '; do not edit: change the protocol file and run `make cwp-ops`.',
    ] + lines


def render_ops(paths):
    out = banner('cwp_ops.inc — Request and Event Numbers, Shared by Server and Clients', paths, [
        '; A message\'s hdr.obj is the interface (CWP_OBJ_* in cwp.inc) and hdr.opcode',
        '; the place of the request or event in that interface.',
        '',
        '%ifndef __CWP_OPS_INC__',
        '%define __CWP_OPS_INC__',
    ])
    seen = {}
    for path in paths:
        for name, requests, events in interfaces(path):
            prefix = re.sub(r'^cw_', '', name).upper()
            out.append('')
            out.append(f'; {name} ({os.path.basename(path)})')
            names = [(f'{prefix}_{r.upper()}', i) for i, r in enumerate(requests)]
            names += [(f'{prefix}_EV_{e.upper()}', i) for i, e in enumerate(events)]
            width = max([len(n) for n, _ in names] + [0]) + 1
            for symbol, index in names:
                if symbol in seen:
                    sys.exit(f'{path}: {symbol} is also defined by {seen[symbol]}')
                seen[symbol] = name
                out.append(f'%define {symbol.ljust(width)}{index}')
    out += ['', '%endif', '']
    return '\n'.join(out)


def render_dispatch(paths):
    out = banner('cwp_dispatch.inc — Every Request, for the Server to Register', paths, [
        '; CWP_REGISTER_ALL invokes CWP_REQUEST interface, request, handler for each',
        '; request whose handler, h_<interface>_<request>, the server has (HAVE_...).',
        '',
        '%ifndef __CWP_DISPATCH_INC__',
        '%define __CWP_DISPATCH_INC__',
        '',
        '%macro CWP_REGISTER_ALL 0',
    ])
    for path in paths:
        for name, requests, events in interfaces(path):
            base = re.sub(r'^cw_', '', name)
            prefix = base.upper()
            for r in requests:
                handler = f'h_{base}_{r}'
                out.append(f'%ifdef HAVE_{handler}')
                out.append(f'    CWP_REQUEST CWP_OBJ_{prefix}, {prefix}_{r.upper()}, {handler}')
                out.append('%endif')
    out += ['%endmacro', '', '%endif', '']
    return '\n'.join(out)


def check_or_write(path, text, check):
    if check:
        try:
            current = open(path, encoding='utf-8').read()
        except FileNotFoundError:
            current = None
        if current != text:
            print(f'cwp-check: {path} is out of date; run make cwp-ops')
            return 1
        return 0
    open(path, 'w', encoding='utf-8', newline='\n').write(text)
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('-o', '--output', required=True)
    parser.add_argument('-d', '--dispatch')
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--handlers')
    parser.add_argument('protocols', nargs='+')
    args = parser.parse_args()
    bad = check_or_write(args.output, render_ops(args.protocols), args.check)
    if args.dispatch:
        bad |= check_or_write(args.dispatch, render_dispatch(args.protocols), args.check)
    if args.handlers:
        wanted = set()
        for path in args.protocols:
            for name, requests, _ in interfaces(path):
                base = re.sub(r'^cw_', '', name)
                wanted |= {f'h_{base}_{r}' for r in requests}
        text = open(args.handlers, encoding='utf-8').read()
        defined = re.findall(r'^\w*HANDLER\s+(h_\w+)', text, re.M)
        for handler in defined:
            if handler not in wanted:
                print(f'cwp-check: {args.handlers}: {handler} handles no request')
                bad = 1
    if args.check and not bad:
        names = args.output + (' and ' + args.dispatch if args.dispatch else '')
        print(f'cwp-check: {names} match {len(args.protocols)} protocol files')
    return bad


if __name__ == '__main__':
    sys.exit(main())
