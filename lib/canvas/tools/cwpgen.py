#!/usr/bin/env python3
"""Generate inc/cwp_ops.inc from the protocol files.

Usage: cwpgen.py [--check] -o inc/cwp_ops.inc proto/a.cwp proto/b.cwp ...

Each request and event gets the number of its place in its interface, as
the wire carries it in hdr.opcode: requests as <INTERFACE>_<REQUEST>, events
as <INTERFACE>_EV_<EVENT>, the interface named without its cw_ prefix. With
--check nothing is written: the exit status is 1 if the file on disk is not
what would be written, so a protocol change cannot leave the numbers behind.

Development-machine tooling only; not part of any OS image.
"""
import argparse
import os
import re
import sys

R_INTERFACE = re.compile(r'^\s*interface\s+(\w+)\s+\d+\s*\{')
R_REQUEST = re.compile(r'^\s*request\s+(\w+)\s*\(')
R_EVENT = re.compile(r'^\s*event\s+(\w+)\s*\(')


def interfaces(path):
    """[(interface, [requests], [events])] in the order the file has them."""
    found = []
    current = None
    depth = 0
    for number, line in enumerate(open(path, encoding='utf-8'), 1):
        code = line.split(';')[0]
        if current is None:
            m = R_INTERFACE.match(code)
            if m:
                current = (m[1], [], [])
                depth = code.count('{') - code.count('}')
            continue
        m = R_REQUEST.match(code)
        if m and depth == 1:
            current[1].append(m[1])
        m = R_EVENT.match(code)
        if m and depth == 1:
            current[2].append(m[1])
        depth += code.count('{') - code.count('}')
        if depth == 0:
            found.append(current)
            current = None
    if current is not None:
        sys.exit(f'{path}: interface {current[0]} is not closed')
    return found


def render(paths):
    out = [
        '; ============================================================================',
        '; cwp_ops.inc — Request and Event Numbers, Shared by Server and Clients',
        '; ============================================================================',
        '; Generated by tools/cwpgen.py from ' + ', '.join(os.path.basename(p) for p in paths) + ';',
        '; do not edit: change the protocol file and run `make cwp-ops`.',
        '; A message\'s hdr.obj is the interface (CWP_OBJ_* in cwp.inc) and hdr.opcode',
        '; the place of the request or event in that interface.',
        '',
        '%ifndef __CWP_OPS_INC__',
        '%define __CWP_OPS_INC__',
    ]
    seen = {}
    for path in paths:
        for name, requests, events in interfaces(path):
            prefix = re.sub(r'^cw_', '', name).upper()
            out.append('')
            out.append(f'; {name} ({os.path.basename(path)})')
            names = [(f'{prefix}_{r.upper()}', i) for i, r in enumerate(requests)]
            names += [(f'{prefix}_EV_{e.upper()}', i) for i, e in enumerate(events)]
            width = max([len(n) for n, _ in names] + [0]) + 1
            for symbol, index in names:
                if symbol in seen:
                    sys.exit(f'{path}: {symbol} is also defined by {seen[symbol]}')
                seen[symbol] = name
                out.append(f'%define {symbol.ljust(width)}{index}')
    out += ['', '%endif', '']
    return '\n'.join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('-o', '--output', required=True)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('protocols', nargs='+')
    args = parser.parse_args()
    text = render(args.protocols)
    if args.check:
        try:
            current = open(args.output, encoding='utf-8').read()
        except FileNotFoundError:
            current = None
        if current != text:
            print(f'cwp-check: {args.output} is out of date; run make cwp-ops')
            return 1
        print(f'cwp-check: {args.output} matches {len(args.protocols)} protocol files')
        return 0
    open(args.output, 'w', encoding='utf-8', newline='\n').write(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
