%macro TOKEN_NODE 2
    mov rdi,rbx
    movzx esi,byte [r12+%1]
    call webp_bool_get
    test eax,eax
    js .token_bad
    jz %2
%endmacro

; WebPBoolReader*,node_probs[11],int32* value -> token or -EINVAL.
global webp_vp8_decode_token
webp_vp8_decode_token:
    PROLOGUE_SAVE rbx,r12,r13,r14,r15
    mov rbx,rdi
    mov r12,rsi
    mov r13,rdx
    test rbx,rbx
    jz .token_bad
    test r12,r12
    jz .token_bad
    test r13,r13
    jz .token_bad
    TOKEN_NODE 0,.token_eob
    TOKEN_NODE 1,.token_zero
    TOKEN_NODE 2,.token_one
    TOKEN_NODE 3,.token_low
    TOKEN_NODE 6,.token_high_low
    TOKEN_NODE 8,.token_cat34
    TOKEN_NODE 10,.token_cat5
    mov r14d,VP8_TOKEN_CAT6
    jmp .token_category
.token_cat5:
    mov r14d,VP8_TOKEN_CAT5
    jmp .token_category
.token_cat34:
    TOKEN_NODE 9,.token_cat3
    mov r14d,VP8_TOKEN_CAT4
    jmp .token_category
.token_cat3:
    mov r14d,VP8_TOKEN_CAT3
    jmp .token_category
.token_high_low:
    TOKEN_NODE 7,.token_cat1
    mov r14d,VP8_TOKEN_CAT2
    jmp .token_category
.token_cat1:
    mov r14d,VP8_TOKEN_CAT1
    jmp .token_category
.token_low:
    TOKEN_NODE 4,.token_two
    TOKEN_NODE 5,.token_three
    mov r14d,VP8_TOKEN_FOUR
    mov r15d,4
    jmp .token_sign
.token_three:
    mov r14d,VP8_TOKEN_THREE
    mov r15d,3
    jmp .token_sign
.token_two:
    mov r14d,VP8_TOKEN_TWO
    mov r15d,2
    jmp .token_sign
.token_one:
    mov r14d,VP8_TOKEN_ONE
    mov r15d,1
    jmp .token_sign
.token_category:
    mov eax,r14d
    sub eax,VP8_TOKEN_CAT1
    lea r10,[rel vp8_category_min]
    movzx r15d,word [r10+rax*2]
    lea r10,[rel vp8_category_bits]
    movzx ecx,byte [r10+rax]
    imul eax,11
    lea r12,[rel vp8_category_probs]
    add r12,rax
    dec ecx
.category_bit:
    mov rdi,rbx
    movzx esi,byte [r12+rcx]
    push rcx
    call webp_bool_get
    pop rcx
    test eax,eax
    js .token_bad
    shl eax,cl
    add r15d,eax
    dec ecx
    jns .category_bit
.token_sign:
    mov rdi,rbx
    mov esi,128
    call webp_bool_get
    test eax,eax
    js .token_bad
    test eax,eax
    jz .token_store
    neg r15d
.token_store:
    mov [r13],r15d
    mov eax,r14d
    EPILOGUE_RESTORE rbx,r12,r13,r14,r15
.token_zero:
    mov dword [r13],0
    mov eax,VP8_TOKEN_ZERO
    EPILOGUE_RESTORE rbx,r12,r13,r14,r15
.token_eob:
    mov dword [r13],0
    mov eax,VP8_TOKEN_EOB
    EPILOGUE_RESTORE rbx,r12,r13,r14,r15
.token_bad:
    mov rax,-EINVAL
    EPILOGUE_RESTORE rbx,r12,r13,r14,r15

; reader,type_probs[8][3][11],coeffs[16],start,initial_context -> end index/-EINVAL.
global webp_vp8_decode_block
webp_vp8_decode_block:
    PROLOGUE_SAVE rbx,r12,r13,r14,r15
    sub rsp,16
    mov rbx,rdi
    mov r12,rsi
    mov r13,rdx
    mov r14d,ecx
    mov r15d,r8d
    test rbx,rbx
    jz .block_bad
    test r12,r12
    jz .block_bad
    test r13,r13
    jz .block_bad
    cmp r14d,15
    ja .block_bad
    cmp r15d,2
    ja .block_bad
    mov rdi,r13
    xor eax,eax
    mov ecx,4
    rep stosq
.block_next:
    lea r10,[rel vp8_coeff_bands]
    movzx eax,byte [r10+r14]
    imul eax,33
    mov edx,r15d
    imul edx,11
    add eax,edx
    lea rsi,[r12+rax]
    mov rdi,rbx
    lea rdx,[rsp]
    call webp_vp8_decode_token
    test eax,eax
    js .block_bad
    cmp eax,VP8_TOKEN_EOB
    je .block_done
    cmp eax,VP8_TOKEN_ZERO
    je .block_zero
    cmp eax,VP8_TOKEN_ONE
    sete r15b
    movzx r15d,r15b
    test r15d,r15d
    jnz .block_store
    mov r15d,2
.block_store:
    lea r10,[rel vp8_coeff_zigzag]
    movzx edx,byte [r10+r14]
    mov eax,[rsp]
    mov [r13+rdx*2],ax
    jmp .block_advance
.block_zero:
    xor r15d,r15d
.block_advance:
    inc r14d
    cmp r14d,16
    jb .block_next
.block_done:
    mov eax,r14d
    add rsp,16
    EPILOGUE_RESTORE rbx,r12,r13,r14,r15
.block_bad:
    mov rax,-EINVAL
    add rsp,16
    EPILOGUE_RESTORE rbx,r12,r13,r14,r15

; reader,current_probs,update_probs,count -> 0/-EINVAL.
global webp_vp8_update_probs
webp_vp8_update_probs:
    PROLOGUE_SAVE rbx,r12,r13,r14
    mov rbx,rdi
    mov r12,rsi
    mov r13,rdx
    mov r14,rcx
    test rbx,rbx
    jz .update_bad
    test r12,r12
    jz .update_bad
    test r13,r13
    jz .update_bad
    xor ecx,ecx
.update_next:
    cmp rcx,r14
    jae .update_done
    mov rdi,rbx
    movzx esi,byte [r13+rcx]
    push rcx
    call webp_bool_get
    pop rcx
    test eax,eax
    js .update_bad
    test eax,eax
    jz .update_skip
    mov rdi,rbx
    mov esi,8
    push rcx
    call webp_bool_literal
    pop rcx
    test eax,eax
    js .update_bad
    mov [r12+rcx],al
.update_skip:
    inc rcx
    jmp .update_next
.update_done:
    xor eax,eax
    EPILOGUE_RESTORE rbx,r12,r13,r14
.update_bad:
    mov rax,-EINVAL
    EPILOGUE_RESTORE rbx,r12,r13,r14

; destination[VP8_COEFF_PROBS_SIZE] -> 0/-EINVAL.
global webp_vp8_coeff_probs_init
webp_vp8_coeff_probs_init:
    test rdi,rdi
    jz .coeff_init_bad
    lea rsi,[rel vp8_default_coeff_probs]
    mov ecx,VP8_COEFF_PROBS_SIZE
    rep movsb
    xor eax,eax
    ret
.coeff_init_bad:
    mov rax,-EINVAL
    ret

