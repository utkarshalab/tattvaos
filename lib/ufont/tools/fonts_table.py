#!/usr/bin/env python3
"""Generate the table of the fonts lib/ufont ships: match/standard.asm for lib/ufont and
tools/standard_data.py for the models.

Usage: fonts_table.py [font directory (default: fonts/)]

Every font file in the directory (a collection: each of its faces) becomes a record - file, face
index, family (the typographic family name, else the family name), weight (OS/2), italic - in
this order: the families listed in FIRST as they are, then the others by family name, the CJK
collections last, Simplified Chinese first (fallback takes the first face that has a character). Each record also carries
its coverage: the code point ranges its cmap maps that Noto Sans Regular's does not, so a font
set can tell which unopened face would have a character without opening it.

match/standard.asm:

    ufont_standard, ufont_standard_count    UfontStd records (include/ufont.inc)
    the file names, family names and coverage ranges (dd first, last) they point to

Development-machine tooling only; not part of any OS image.
"""
import os
import sys

from fontTools.ttLib import TTFont, TTCollection

HERE = os.path.dirname(os.path.abspath(__file__))

# the order fallback has always had: Latin, Liberation, then the Indic, Arabic and Hebrew faces
FIRST = ['NotoSans-Regular.ttf', 'NotoSans-Bold.ttf', 'NotoSans-Italic.ttf', 'NotoSans-BoldItalic.ttf',
         'NotoSerif-Regular.ttf', 'NotoSerif-Bold.ttf', 'NotoSerif-Italic.ttf', 'NotoSerif-BoldItalic.ttf',
         'NotoSansMono-Regular.ttf', 'NotoSansMono-Bold.ttf',
         'LiberationSans-Regular.ttf', 'LiberationSans-Bold.ttf', 'LiberationSans-Italic.ttf',
         'LiberationSans-BoldItalic.ttf', 'LiberationSerif-Regular.ttf', 'LiberationSerif-Bold.ttf',
         'LiberationSerif-Italic.ttf', 'LiberationSerif-BoldItalic.ttf', 'LiberationMono-Regular.ttf',
         'LiberationMono-Bold.ttf', 'LiberationMono-Italic.ttf', 'LiberationMono-BoldItalic.ttf',
         'NotoSansDevanagari-Regular.ttf', 'NotoSansDevanagari-Bold.ttf', 'NotoSerifDevanagari-Regular.ttf',
         'NotoSerifDevanagari-Bold.ttf', 'NotoSansBengali-Regular.ttf', 'NotoSansBengali-Bold.ttf',
         'NotoSansGurmukhi-Regular.ttf', 'NotoSansGurmukhi-Bold.ttf', 'NotoSansGujarati-Regular.ttf',
         'NotoSansGujarati-Bold.ttf', 'NotoSansOriya-Regular.ttf', 'NotoSansOriya-Bold.ttf',
         'NotoSansTamil-Regular.ttf', 'NotoSansTamil-Bold.ttf', 'NotoSansTelugu-Regular.ttf',
         'NotoSansTelugu-Bold.ttf', 'NotoSansKannada-Regular.ttf', 'NotoSansKannada-Bold.ttf',
         'NotoSansMalayalam-Regular.ttf', 'NotoSansMalayalam-Bold.ttf', 'NotoSansArabic-Regular.ttf',
         'NotoSansArabic-Bold.ttf', 'NotoNaskhArabic-Regular.ttf', 'NotoNaskhArabic-Bold.ttf',
         'NotoSansHebrew-Regular.ttf', 'NotoSansHebrew-Bold.ttf', 'NotoSerifHebrew-Regular.ttf',
         'NotoSerifHebrew-Bold.ttf']


# CJK faces by region: Simplified Chinese first (what fallback takes for Han without a language),
# then Traditional, Hong Kong, Japanese, Korean; the Mono ones after
CJK_ORDER = ['SC', 'TC', 'HK', 'JP', 'KR']


def faces(path):
    """[(face index, TTFont)] of a font file."""
    if path.endswith(('.ttc', '.otc')):
        return list(enumerate(TTCollection(path).fonts))
    return [(0, TTFont(path))]


def describe(f):
    name = f['name']
    family = name.getDebugName(16) or name.getDebugName(1)
    weight = f['OS/2'].usWeightClass
    italic = 1 if f['OS/2'].fsSelection & 1 else 0
    return family, weight, italic


def ranges(cps):
    out = []
    for u in sorted(cps):
        if out and out[-1][1] == u - 1:
            out[-1][1] = u
        else:
            out.append([u, u])
    return out


def main():
    directory = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, '..', 'fonts')
    files = [f for f in os.listdir(directory) if f.endswith(('.ttf', '.otf', '.ttc', '.otc'))]
    base = set(TTFont(os.path.join(directory, 'NotoSans-Regular.ttf')).getBestCmap())
    records = []
    for fname in files:
        for index, f in faces(os.path.join(directory, fname)):
            family, weight, italic = describe(f)
            cover = ranges(set(f.getBestCmap()) - base)
            records.append((fname, index, family, weight, italic, cover))
    first = {n: i for i, n in enumerate(FIRST)}

    def order(r):
        cjk = 'CJK' in r[0]
        region = next((k for k, reg in enumerate(CJK_ORDER) if r[2].endswith(' ' + reg)), 0) if cjk else 0
        return (r[0] not in first, first.get(r[0], 0), cjk, 'Mono' in r[2] if cjk else False, region,
                r[2].lower(), r[0], r[1])
    records.sort(key=order)
    # the models' copy
    lines = ['"""The fonts lib/ufont ships, in ufont_standard\'s order - generated by tools/fonts_table.py;',
             'do not edit.', '',
             'STANDARD: [(file, face index, family, weight, italic)]."""', 'STANDARD = [']
    for fname, index, family, weight, italic, _ in records:
        lines.append(f'    ({fname!r}, {index}, {family!r}, {weight}, {italic}),')
    lines.append(']')
    open(os.path.join(HERE, 'standard_data.py'), 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
    # lib/ufont's
    families = sorted({r[2] for r in records})
    fam_label = {fam: f'fsd_{i}' for i, fam in enumerate(families)}
    file_names = sorted({r[0] for r in records})
    file_label = {fn: f'fsn_{i}' for i, fn in enumerate(file_names)}
    out = ['; =============================================================================',
           '; Utkarsha OS — lib/ufont/match/standard.asm',
           '; =============================================================================',
           "; The fonts lib/ufont ships (fonts/), generated by tools/fonts_table.py from",
           '; the font files; do not edit. UfontStd records: file, family, weight,',
           '; italic, face index, coverage (dd first, last per range: what the face has',
           '; beyond Noto Sans Regular) and how many ranges.',
           '; =============================================================================',
           '',
           '%include "ufont.inc"',
           '',
           'section .rodata',
           'align 8',
           'global ufont_standard', 'global ufont_standard_count',
           f'ufont_standard_count: dq {len(records)}',
           'ufont_standard:']
    # faces with the same coverage (a collection's regions, a family's weights) share it
    covers = {}
    for r in records:
        if r[5]:
            covers.setdefault(tuple(map(tuple, r[5])), f'fsc_{len(covers)}')
    for fname, index, family, weight, italic, cover in records:
        out.append(f'    dq {file_label[fname]}, {fam_label[family]}')
        out.append(f'    dd {weight}, {italic}, {index}, {len(cover)}')
        out.append(f'    dq {covers[tuple(map(tuple, cover))] if cover else 0}')
    out.append('align 4')
    for cover, label in covers.items():
        out.append(f'{label}:')
        for k in range(0, len(cover), 4):
            out.append('    dd ' + ', '.join(f'0x{a:X}, 0x{b:X}' for a, b in cover[k:k + 4]))
    for fam in families:
        out.append(f'{fam_label[fam]}: db "{fam}", 0')
    for fn in file_names:
        out.append(f'{file_label[fn]}: db "{fn}", 0')
    path = os.path.join(HERE, '..', 'match', 'standard.asm')
    open(path, 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
    print(f'{len(records)} faces, {len(families)} families, '
          f'{sum(len(c) for c in covers)} coverage ranges ({len(covers)} lists)')


if __name__ == '__main__':
    main()
