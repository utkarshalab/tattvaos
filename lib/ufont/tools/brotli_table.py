#!/usr/bin/env python3
"""Generate Brotli's tables from RFC 7932 (development machine only).

Usage: brotli_table.py <rfc7932.txt> <dictionary.bin>

The literal context lookup tables Lut0, Lut1, Lut2 (section 7.1) and the
121 word transforms (Appendix B) are read from the RFC's text; every one,
and the static dictionary (122,784 bytes, the RFC's Appendix A as a file),
is checked against the CRC-32 the RFC gives. Writes:

- sfnt/brotli_tables.asm: the lookup tables, the transforms (prefix,
  type, suffix offsets into a string pool), the dictionary's word sizes;
- include/brotli_dict.bin: the dictionary (sfnt/brotli.asm incbins it);
- tools/brotli_data.py: the same for tools/brotlimodel.py.
"""
import ast
import os
import re
import sys
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..')

CRCS = {'Lut0': 0x8e91efb7, 'Lut1': 0xd01a32f4, 'Lut2': 0x0dd7a0d6}
DICT_CRC, DICT_LEN = 0x5136cb04, 122784
TRANSFORMS_CRC, TRANSFORMS_LEN = 0x3d965f81, 648
TYPES = ['Identity', 'FermentFirst', 'FermentAll'] + ['OmitFirst%d' % i for i in range(1, 10)] + \
        ['OmitLast%d' % i for i in range(1, 10)]
NDBITS = [0, 0, 0, 0, 10, 10, 11, 11, 10, 10, 10, 10, 10, 9, 9, 8, 7, 7, 8, 7, 7, 6, 6, 5, 5]


def pages(text):
    """The RFC without its page breaks (footer, form feed, header)."""
    out = []
    for line in text.splitlines():
        if line.startswith('\f') or re.match(r'^(Alakuijala & Szabadka|RFC 7932 )', line):
            continue
        out.append(line)
    return out


def table(lines, name):
    i = next(k for k, l in enumerate(lines) if l.strip() == name + ' :=')
    vals = []
    for l in lines[i + 1:]:
        nums = re.findall(r'\d+', l)
        if not nums:
            if vals:
                break
            continue
        vals += [int(n) for n in nums]
        if len(vals) >= 256:
            break
    assert len(vals) == 256, name
    assert zlib.crc32(bytes(vals)) == CRCS[name], name
    return vals


def transforms(lines):
    i = next(k for k, l in enumerate(lines) if l.strip().startswith('ID') and 'Prefix' in l)
    out = []
    for l in lines[i + 2:]:
        m = re.match(r'^\s*(\d+)\s+("(?:[^"\\]|\\.)*")\s+(\w+)\s+("(?:[^"\\]|\\.)*")\s*$', l)
        if not m:
            if out and l.strip() and not l.strip().startswith('ID'):
                break
            continue
        tid = int(m.group(1))
        assert tid == len(out)
        pre = ast.literal_eval(m.group(2)).encode('latin-1')
        suf = ast.literal_eval(m.group(4)).encode('latin-1')
        out.append((pre, TYPES.index(m.group(3)), suf))
        if tid == 120:
            break
    blob = b''.join(p + b'\0' + bytes([t]) + s + b'\0' for p, t, s in out)
    assert len(out) == 121 and len(blob) == TRANSFORMS_LEN and zlib.crc32(blob) == TRANSFORMS_CRC
    return out


def rows(kind, vals, per=16):
    return [f'    {kind} ' + ', '.join(str(v) for v in vals[i:i + per]) for i in range(0, len(vals), per)]


def main():
    lines = pages(open(sys.argv[1], encoding='utf-8').read())
    dictionary = open(sys.argv[2], 'rb').read()
    assert len(dictionary) == DICT_LEN and zlib.crc32(dictionary) == DICT_CRC
    luts = {n: table(lines, n) for n in ('Lut0', 'Lut1', 'Lut2')}
    tr = transforms(lines)
    # dictionary offsets by word length
    offsets, at = [0] * 25, 0
    for n in range(4, 25):
        offsets[n] = at
        at += n << NDBITS[n]
    assert at == DICT_LEN
    pool, places = b'', []
    for pre, t, suf in tr:
        places.append((len(pool), len(pre), t, len(pool) + len(pre), len(suf)))
        pool += pre + suf
    out = ['; =============================================================================',
           '; Utkarsha OS — lib/ufont/sfnt/brotli_tables.asm',
           '; =============================================================================',
           '; Brotli\'s tables (RFC 7932), generated by tools/brotli_table.py from the',
           '; RFC\'s text and checked against its CRC-32 values; do not edit.',
           ';',
           ';   ufl_br_lut0 / lut1 / lut2     the literal context lookups (section 7.1)',
           ';   ufl_br_ndbits, ufl_br_dictoff by word length 0..24: the dictionary\'s',
           ';                                 index bits and where its words start',
           ';   ufl_br_transforms             121 x (u16 prefix at, u8 prefix length, u8',
           ';                                 type: 0 identity, 1 / 2 uppercase first / all,',
           ';                                 3..11 omit first 1..9, 12..20 omit last 1..9,',
           ';                                 u16 suffix at, u8 suffix length, u8 0) into',
           ';   ufl_br_pool                   the prefixes and suffixes',
           ';   ufl_br_dict                   the static dictionary (include/brotli_dict.bin)',
           '; =============================================================================',
           '',
           'section .rodata',
           '']
    for n in ('Lut0', 'Lut1', 'Lut2'):
        out += [f'global ufl_br_{n.lower()}', f'ufl_br_{n.lower()}:'] + rows('db', luts[n])
    out += ['global ufl_br_ndbits', 'ufl_br_ndbits:'] + rows('db', NDBITS, 25)
    out += ['align 4', 'global ufl_br_dictoff', 'ufl_br_dictoff:'] + rows('dd', offsets, 25)
    out += ['align 4', 'global ufl_br_transforms', 'ufl_br_transforms:']
    for a, la, t, b, lb in places:
        out.append(f'    dw {a}')
        out.append(f'    db {la}, {t}')
        out.append(f'    dw {b}')
        out.append(f'    db {lb}, 0')
    out += ['global ufl_br_pool', 'ufl_br_pool:'] + rows('db', list(pool))
    out += ['align 8', 'global ufl_br_dict', 'ufl_br_dict:', '    incbin "brotli_dict.bin"', '']
    open(os.path.join(ROOT, 'sfnt', 'brotli_tables.asm'), 'w', encoding='utf-8', newline='\n').write(
        '\n'.join(out) + '\n')
    open(os.path.join(ROOT, 'include', 'brotli_dict.bin'), 'wb').write(dictionary)
    data = ['"""Brotli\'s tables (RFC 7932) for tools/brotlimodel.py - generated by tools/brotli_table.py; do not edit."""',
            f'LUT0 = {luts["Lut0"]!r}', f'LUT1 = {luts["Lut1"]!r}', f'LUT2 = {luts["Lut2"]!r}',
            f'NDBITS = {NDBITS!r}', f'DICT_OFFSETS = {offsets!r}', 'TRANSFORMS = [']
    data += [f'    ({p!r}, {t}, {s!r}),' for p, t, s in tr]
    data.append(']')
    open(os.path.join(HERE, 'brotli_data.py'), 'w', encoding='utf-8', newline='\n').write('\n'.join(data) + '\n')
    print('tables, 121 transforms and the dictionary checked')


if __name__ == '__main__':
    main()
